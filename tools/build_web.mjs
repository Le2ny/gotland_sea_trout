// Prepares www/ to run as an installable web app (iPhone: Safari → "Zum Home-Bildschirm").
// - renders home-screen icons from www/icon.svg (apple-touch-icon, 192/512, maskable)
// - writes www/manifest.webmanifest
// - writes www/sw.js: caches every app file (versioned by content hash), so the app starts
//   offline. Live data (Copernicus, Open-Meteo) is never cached by the service worker:
//   the forecast lives in IndexedDB, viewed map tiles in their own cache (basemap.js).
// Run after any change in www/:  node tools/build_web.mjs
import fs from 'node:fs'; import path from 'node:path'; import crypto from 'node:crypto';
import { chromium } from 'playwright';

const www = new URL('../www/', import.meta.url).pathname;
const svg = fs.readFileSync(www + 'icon.svg', 'utf8');
fs.mkdirSync(www + 'img', { recursive: true });

// icons
const fishOnly = svg.replace(/<rect[^>]*\/>/, '').replace('viewBox="0 0 512 512"', 'viewBox="-110 -110 732 732"');
const b = await chromium.launch(); const p = await b.newPage();
async function render(src, px, file, bg) {
  await p.setViewportSize({ width: px, height: px });
  await p.setContent(`<html><body style="margin:0;background:${bg || 'transparent'}">${src.replace('<svg ', `<svg width="${px}" height="${px}" style="display:block" `)}</body></html>`);
  await p.screenshot({ path: www + 'img/' + file, omitBackground: !bg });
}
await render(fishOnly, 180, 'apple-touch-icon.png', '#0b3d4d');   // iOS adds its own rounded corners
await render(svg, 192, 'icon-192.png');
await render(svg, 512, 'icon-512.png');
await render(fishOnly, 512, 'icon-maskable-512.png', '#0b3d4d');
await b.close();

fs.writeFileSync(www + 'manifest.webmanifest', JSON.stringify({
  name: 'Gotland Sea Trout', short_name: 'Sea Trout', lang: 'de',
  description: 'Strömung, Spots und Wetter für Meerforellenangler auf Gotland – offline nutzbar.',
  start_url: './', scope: './', display: 'standalone', orientation: 'portrait',
  background_color: '#06222c', theme_color: '#0b3d4d',
  icons: [
    { src: 'img/icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'img/icon-512.png', sizes: '512x512', type: 'image/png' },
    { src: 'img/icon-maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
}, null, 2));

// service worker with the full file list
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, e.name), rel = path.relative(www, full).split(path.sep).join('/');
    if (e.isDirectory()) walk(full);
    else if (!['sw.js', 'js/package.json'].includes(rel) && !rel.startsWith('.')) files.push(rel);
  }
})(www);
files.sort();
const hash = crypto.createHash('sha256');
for (const f of files) hash.update(f).update(fs.readFileSync(www + f));
const version = hash.digest('hex').slice(0, 12);

fs.writeFileSync(www + 'sw.js', `// generated by tools/build_web.mjs – do not edit
const CACHE = 'app-${version}';
const FILES = ${JSON.stringify(['./', ...files], null, 0)};

self.addEventListener('install', e => {
  // all files or nothing: a half-downloaded update never replaces the working version
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES.map(f => new Request(f, { cache: 'reload' })))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('app-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', e => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== self.location.origin) return;  // live data: straight to the network
  e.respondWith(caches.open(CACHE).then(async c => {
    const hit = await c.match(e.request, { ignoreSearch: true }) || (e.request.mode === 'navigate' && await c.match('./'));
    return hit || fetch(e.request);
  }));
});
`);
console.log(`web build: ${files.length} files, cache app-${version}`);
