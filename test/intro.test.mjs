// Intro: coin toss result with a loaded forecast, auto close, "So funktioniert's".
import { chromium, webkit } from 'playwright';
import http from 'node:http'; import fs from 'node:fs'; import path from 'node:path';
const engine = process.env.ENGINE === 'webkit' ? webkit : chromium;
const root = new URL('../www/', import.meta.url).pathname, out = process.argv[2] || '.';
const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.png': 'image/png', '.jpg': 'image/jpeg', '.svg': 'image/svg+xml', '.webmanifest': 'application/manifest+json' };
const srv = http.createServer((q, s) => { const f = path.join(root, decodeURIComponent(q.url.split('?')[0]).replace(/\/$/, '/index.html'));
  fs.readFile(f, (e, d) => { if (e) { s.writeHead(404); s.end(); } else { s.writeHead(200, { 'content-type': types[path.extname(f)] || 'application/octet-stream' }); s.end(d); } }); }).listen(8766);
const b = await engine.launch(); const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2.5, hasTouch: true });
const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
await p.goto('http://localhost:8766/'); await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/I-0-noforecast.png` });
console.log('intro line:', await p.textContent('.introUi .tag'));
await p.click('#coin', { force: true }); await p.waitForTimeout(1900);
console.log('coin without forecast:', await p.textContent('#coinHint'));
await p.click('#introGo'); await p.waitForTimeout(900);
console.log('intro closed:', !(await p.$('#intro')));
await p.click('#btnLoad'); await p.waitForFunction(() => /Fertig|Fehler/.test(document.getElementById('progressText').textContent), null, { timeout: 300000 });
await p.reload(); await p.waitForTimeout(1200);
await p.click('#coin', { force: true }); await p.waitForTimeout(500); await p.screenshot({ path: `${out}/I-1-flying.png` }); await p.waitForTimeout(1400);
console.log('coin result:', (await p.textContent('#coinHint')).replace(/\s+/g, ' '));
await p.screenshot({ path: `${out}/I-2-result.png` });
await p.click('#coinGo'); await p.waitForTimeout(1200);
console.log('opened spot:', await p.textContent('#sheetTitle'));
await p.reload(); await p.waitForTimeout(5200);
console.log('auto-closed after ~3.6 s without touch:', !(await p.$('#intro')));
await p.reload(); await p.waitForTimeout(1000); await p.click('#introHow'); await p.waitForTimeout(900);
console.log('how sheet:', await p.textContent('#sheetTitle'), '·', (await p.$$eval('#sheetBody h4', e => e.map(x => x.textContent))).join(' / '));
await p.screenshot({ path: `${out}/I-3-how.png` });
console.log('errors:', errs.join(' | ') || 'none');
await b.close(); srv.close();
